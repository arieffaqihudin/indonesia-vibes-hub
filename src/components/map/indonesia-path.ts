/**
 * A deliberately simplified archipelago outline, drawn from coarse
 * lat/lng polygons rather than a full geodata file. It is an editorial
 * diagram of Indonesia, not a survey map.
 */

export const IDN_BOUNDS = { west: 94, east: 142, north: 7, south: -12 };

export const projectIdn = (lat: number, lng: number) => ({
  x: ((lng - IDN_BOUNDS.west) / (IDN_BOUNDS.east - IDN_BOUNDS.west)) * 1000,
  y: ((IDN_BOUNDS.north - lat) / (IDN_BOUNDS.east - IDN_BOUNDS.west)) * 1000,
});

