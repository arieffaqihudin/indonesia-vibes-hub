export const INDONESIA_PATH = ISLANDS.map((ring) =>
  ring
    .map(([lng, lat], i) => {
      const { x, y } = projectIdn(lat, lng);
      return `${i === 0 ? "M" : "L"}${x.toFixed(1)},${y.toFixed(1)}`;
    })
    .join(" ")
    .concat(" Z"),
).join(" ");
