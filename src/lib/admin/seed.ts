const DAY = 86_400_000;
export const at = (offsetDays: number, hour = 10) => {
  const d = new Date(Date.now() + offsetDays * DAY);
  d.setHours(hour, offsetDays % 2 ? 42 : 18, 0, 0);
  return d.toISOString();
};

