const rel = (partial: Partial<Relationships>): Relationships => ({ ...emptyRelationships(), ...partial });

let n = 0;
const nextId = (prefix: string) => `${prefix}-${++n}`;

const reviewDates = (publishedOffset: number, frequency: number) => ({
  publishedAt: at(publishedOffset),
  lastReviewed: at(publishedOffset + Math.round(frequency / 3)),
  nextReview: at(publishedOffset + frequency),
  reviewFrequencyDays: frequency,
});

function published(
  kind: ContentKind,
  source: { id: string; slug?: string },
  title: string,
  opts: {
    path: string;
    themes?: string[];
    countries?: string[];
    location?: string;
    editor: string;
    offset: number;
    frequency: number;
    fields: Record<string, string>;
    relationships?: Partial<Relationships>;
    deliveryType?: ContentItem["deliveryType"];
    contentSource?: ContentItem["contentSource"];
    topics?: string[];
    sourceAttribution?: string;
  },
): ContentItem {
  return {
    id: `c-${source.id}`,
    kind,
    ...(opts.deliveryType ? { deliveryType: opts.deliveryType } : {}),
    ...(opts.contentSource ? { contentSource: opts.contentSource } : {}),
    ...(opts.topics ? { topics: opts.topics } : {}),
    ...(opts.sourceAttribution ? { sourceAttribution: opts.sourceAttribution } : {}),
    title,
    ...(source.slug ? { slug: source.slug } : {}),
    publicPath: opts.path,
    status: "published",
    priority: "Normal",
    assignedTo: opts.editor,
    themes: opts.themes ?? [],
    countries: opts.countries ?? ["Indonesia"],
    ...(opts.location ? { location: opts.location } : {}),
    createdAt: at(opts.offset - 30),
    updatedAt: at(opts.offset + 2),
    stageSince: at(opts.offset),
    ...reviewDates(opts.offset, opts.frequency),
    fields: opts.fields,
    relationships: rel(opts.relationships ?? {}),
    culturalReview: { flags: [], decision: "No concern", reviewer: "Wayan Sudarma", date: at(opts.offset - 4) },
    languageReview: { complete: true, reviewer: "Claire Whitfield", date: at(opts.offset - 3) },
    feedback: [],
    notes: [],
    versions: [
      { id: nextId("v"), label: "v1", editor: opts.editor, date: at(opts.offset - 20), summary: "First editorial pass from the contributor draft." },
      { id: nextId("v"), label: "v2", editor: "Claire Whitfield", date: at(opts.offset - 3), summary: "Language review: terminology and geographic references." },
      { id: nextId("v"), label: "v3", editor: opts.editor, date: at(opts.offset), summary: "Published." },
    ],
    prototype: true,
  };
}

